"""Vantage DD management CLI — works the same on Windows (PowerShell / cmd) and macOS/Linux.

    python scripts/manage.py setup                 # create .env with random secrets (dev/demo)
    python scripts/manage.py check-config          # validate settings (fails on unsafe production config)
    python scripts/manage.py migrate               # apply pending migrations (backup written first)
    python scripts/manage.py migrate --new-only    # create a new DB; never touch an existing one
    python scripts/manage.py create-admin --email you@firm.com --name "Your Name"
    python scripts/manage.py add-real-deal --cik 716006 --fy 2022 --name "Yellow FY2022" --owner you@firm.com
    python scripts/manage.py backup                # consistent backup -> backups/vantage-backup-<UTC>.zip
    python scripts/manage.py restore backups/vantage-backup-....zip
    python scripts/manage.py verify-audit          # recompute the audit hash chain
    python scripts/manage.py inspect-db --path backend/vantage.db   # read-only: tables, counts, revision, integrity
    python scripts/manage.py doctor                # dependency / import check
    python scripts/manage.py reset-dev             # move local dev data aside (never deletes; refused in prod)
"""
