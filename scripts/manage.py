def _random_password(n: int = 16) -> str:
    alphabet = string.ascii_letters + string.digits
    while True:
        p = "".join(secrets.choice(alphabet) for _ in range(n - 2)) + secrets.choice("!#%+") + secrets.choice(string.digits)
        if any(c.isupper() for c in p) and any(c.islower() for c in p):
            return p


def cmd_setup(_):
    env = ROOT / ".env"
    if env.exists():
        print(f".env already exists at {env}; not overwriting. Delete it first to regenerate.")
        return 0
    pw = _random_password()
    env.write_text("\n".join([
        "# Generated by scripts/manage.py setup — local development / demo only. Do not commit.",
        "VANTAGE_ENV=dev",
        "VANTAGE_DEMO_MODE=true",
        f"VANTAGE_JWT_SECRET={secrets.token_urlsafe(48)}",
        f"VANTAGE_SEED_PASSWORD={pw}",
        "VANTAGE_SOURCE_MODE=snapshot",
        "# For live SEC refresh set: VANTAGE_SOURCE_MODE=live and VANTAGE_SEC_USER_AGENT=Your Name your@email.com",
        "VANTAGE_LLM_PROVIDER=offline", ""]), encoding="utf-8")
    print(f"Created {env}")
    print("Demo accounts: analyst@vantage.dev, partner@vantage.dev, admin@vantage.dev")
    print(f"Demo password (shown once, also stored only in your local .env): {pw}")
    return 0


def _settings():
    from app.core.config import get_settings
    return get_settings()


def cmd_check_config(_):
    from app.core.config import ConfigError, validate_settings
    s = _settings()
    try:
        warnings = validate_settings(s)
    except ConfigError as exc:
        print(f"CONFIG ERROR: {exc}")
        return 2
    print(f"OK (env={s.env}, demo_mode={s.demo_mode}, source_mode={s.source_mode}, db={s.database_url.split(':')[0]})")
    for w in warnings:
        print(f"WARNING: {w}")
    return 0


def cmd_migrate(a):
    """Apply migrations. With --new-only, only a missing/empty database is created; an existing database is
    inspected read-only and left untouched (used by setup scripts)."""
    from app.db.seed import _sqlite_path, init_db, inspect_sqlite_readonly
    if getattr(a, "new_only", False):
        p = _sqlite_path()
        if p is not None and p.stat().st_size > 0:
            info = inspect_sqlite_readonly(p)
            print(f"Existing database {p} left untouched (revision {info['alembic_revision'] or 'none/unversioned'}, "
                  f"integrity {info['integrity']}). To upgrade it, test on a copy first, then run "
                  "`python scripts/manage.py migrate` (writes a backup first).")
            return 0
    try:
        init_db()
    except RuntimeError as exc:
        print(f"REFUSED: {exc}")
        return 2
    print("Database is at the latest migration.")
    return 0


def cmd_create_admin(a):
    from app.core.security import hash_password, password_policy_errors
    from app.db.audit import write_audit
    from app.db.models import User
    from app.db.seed import init_db
    from app.db.session import SessionLocal
    init_db()
    pw = getpass.getpass("New admin password: ")
    if pw != getpass.getpass("Repeat password: "):
        print("Passwords do not match")
        return 1
    if errs := password_policy_errors(pw):
        print("Password must contain " + ", ".join(errs))
        return 1
    with SessionLocal() as db:
        if db.query(User).filter_by(email=a.email.lower()).first():
            print("User already exists")
            return 1
        u = User(email=a.email.lower(), full_name=a.name, role="admin", hashed_password=hash_password(pw))
        db.add(u)
        db.commit()
        write_audit(db, user_id=None, user_email="cli", action="user_created", resource=f"user:{u.id}",
                    detail={"email": u.email, "role": "admin"})
    print(f"Admin {a.email} created.")
    return 0


def cmd_add_real_deal(a):
    from app.db.audit import write_audit
    from app.db.models import User
    from app.db.seed import init_db
    from app.db.session import SessionLocal
    from app.sources.real_deals import build_real_deal
    init_db()
    with SessionLocal() as db:
        owner = db.query(User).filter_by(email=a.owner.lower()).first()
        if not owner:
            print("Owner user not found")
            return 1
        members = [u.id for u in db.query(User).filter(User.email.in_([m.lower() for m in a.member or []]))]
        rep = build_real_deal(db, cik=a.cik, fiscal_year=a.fy, name=a.name, deal_type=a.type, sector=a.sector,
                              owner_id=owner.id, member_ids=members, mode="live" if a.live else None)
        db.commit()
        write_audit(db, user_id=owner.id, user_email="cli", action="real_deal_built", resource=f"deal:{rep.deal_id}",
                    detail={"cik": a.cik, "fy": a.fy, "accession": rep.accession, "facts": rep.facts_written,
                            "missing": rep.facts_missing, "warnings": rep.warnings})
    print(json.dumps(rep.__dict__, indent=2, default=str))
    return 0


def _sqlite_path(url: str) -> Path | None:
    return Path(url.replace("sqlite:///", "", 1)) if url.startswith("sqlite:///") else None


def _sqlite_copy(src: Path, dst: Path) -> None:
    """Online, transactionally consistent copy (safe while the API runs); the source is opened read-only and the
    copy is a single self-contained file (no -wal/-shm sidecars)."""
    a = sqlite3.connect(src.resolve().as_uri() + "?mode=ro", uri=True)
    b = sqlite3.connect(dst)
    try:
        a.backup(b)
        b.execute("PRAGMA journal_mode=DELETE")
    finally:
        b.close()
        a.close()


def _with_sidecars(p: Path) -> list[Path]:
    return [p, Path(str(p) + "-wal"), Path(str(p) + "-shm")]


def cmd_backup(_):
    s = _settings()
    db_path = _sqlite_path(s.database_url)
    if db_path is None:
        print("Postgres: use pg_dump (see docs/OPERATIONS.md). This command backs up SQLite deployments.")
        return 1
    stamp = datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%SZ")
    s.backup_dir.mkdir(parents=True, exist_ok=True)
    work = s.backup_dir / f"tmp-{stamp}"
    work.mkdir()
    manifest = {"created_at": stamp, "files": {}}
    for src in (db_path, s.checkpoint_db):
        if src.exists():
            dst = work / src.name
            _sqlite_copy(src, dst)
    for folder in (s.storage_dir, s.vector_index_dir):
        if folder.exists():
            shutil.copytree(folder, work / folder.name)
    out = s.backup_dir / f"vantage-backup-{stamp}.zip"
    with zipfile.ZipFile(out, "w", zipfile.ZIP_DEFLATED) as z:
        for p in sorted(work.rglob("*")):
            if p.is_file():
                rel = p.relative_to(work).as_posix()
                manifest["files"][rel] = hashlib.sha256(p.read_bytes()).hexdigest()
                z.write(p, rel)
        z.writestr("backup_manifest.json", json.dumps(manifest, indent=1))
    shutil.rmtree(work)
    print(f"Backup written: {out} ({len(manifest['files'])} files). Source snapshots are in data/source_snapshots "
          "and are content-addressed; back that folder up with your code.")
    return 0


def cmd_restore(a):
    s = _settings()
    db_path = _sqlite_path(s.database_url)
    z = zipfile.ZipFile(a.archive)
    manifest = json.loads(z.read("backup_manifest.json"))
    for rel, sha in manifest["files"].items():
        if hashlib.sha256(z.read(rel)).hexdigest() != sha:
            print(f"Backup integrity check failed for {rel}; nothing restored.")
            return 2
    if not a.yes and input("Stop the API first. Restore and replace current data? [y/N] ").lower() != "y":
        return 1
    aside = s.backup_dir / f"pre-restore-{datetime.now(timezone.utc).strftime('%Y%m%dT%H%M%SZ')}"
    aside.mkdir(parents=True)
    targets = {db_path.name: db_path, s.checkpoint_db.name: s.checkpoint_db}
    # move current files aside (never deleted) — including WAL/SHM sidecars, which SQLite would otherwise
    # replay onto the restored database
    for p in [*_with_sidecars(db_path), *_with_sidecars(s.checkpoint_db), s.storage_dir, s.vector_index_dir]:
        if p.exists():
            shutil.move(str(p), str(aside / p.name))
    for rel in manifest["files"]:
        top = rel.split("/")[0]
        dest = targets.get(rel) or ({s.storage_dir.name: s.storage_dir.parent, s.vector_index_dir.name:
                                     s.vector_index_dir.parent}[top] / rel)
        dest.parent.mkdir(parents=True, exist_ok=True)
        dest.write_bytes(z.read(rel))
    print(f"Restored {len(manifest['files'])} files from {a.archive}. Previous data moved to {aside}.")
    return 0


