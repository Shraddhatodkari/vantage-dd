def cmd_reset_dev(a):
    s = _settings()
    if s.env == "prod":
        print("Refused: reset-dev is disabled in production.")
        return 2
    db_path = _sqlite_path(s.database_url)
    if db_path is None:
        print("Refused: reset-dev only applies to a local SQLite development database.")
        return 2
    if not a.yes and input(f"Move {db_path.name}, checkpoints, storage and index aside (nothing is deleted)? [y/N] ").lower() != "y":
        return 1
    aside = s.backup_dir / f"pre-reset-{datetime.now(timezone.utc).strftime('%Y%m%dT%H%M%SZ')}"
    aside.mkdir(parents=True)
    moved = 0
    for p in [*_with_sidecars(db_path), *_with_sidecars(s.checkpoint_db), s.storage_dir, s.vector_index_dir]:
        if p.exists():
            shutil.move(str(p), str(aside / p.name))
            moved += 1
    print(f"Moved {moved} item(s) to {aside} (nothing deleted). Start the API to create a fresh database.")
    return 0


def cmd_inspect_db(a):
    """Read-only description of any SQLite file: tables, row counts, migration revision, integrity. Never writes."""
    from app.db.seed import inspect_sqlite_readonly
    path = Path(a.path)
    if not path.exists():
        print(f"Not found: {path}")
        return 1
    before = hashlib.sha256(path.read_bytes()).hexdigest()
    info = inspect_sqlite_readonly(path)
    info["sha256"] = before
    info["unchanged_after_inspection"] = hashlib.sha256(path.read_bytes()).hexdigest() == before
    info["migration_status"] = ("unversioned (pre-migration schema: the app will refuse to modify it)"
                                if info["alembic_revision"] is None and "users" in info["tables"] else
                                f"alembic revision {info['alembic_revision']}")
    print(json.dumps(info, indent=2, default=str))
    return 0


DOCTOR_IMPORTS = ["fastapi", "uvicorn", "sqlalchemy", "alembic", "pydantic_settings", "bcrypt", "jwt", "httpx",
                  "langgraph", "langgraph.checkpoint.sqlite", "langchain_core", "mcp", "numpy", "multipart"]
OPTIONAL_IMPORTS = ["mlflow", "peft", "transformers", "torch", "sentence_transformers", "anthropic", "playwright"]


def cmd_doctor(_):
    """Check Python version, required/optional packages and that the app imports. Read-only."""
    import importlib
    ok = sys.version_info >= (3, 11)
    print(f"python {sys.version.split()[0]}: {'OK' if ok else 'NEEDS >= 3.11'}")
    for mod in DOCTOR_IMPORTS:
        try:
            importlib.import_module(mod)
            print(f"  required {mod}: OK")
        except Exception as exc:  # noqa: BLE001
            ok = False
            print(f"  required {mod}: MISSING ({type(exc).__name__}) -> pip install -r backend/requirements.txt")
    for mod in OPTIONAL_IMPORTS:
        try:
            importlib.import_module(mod)
            print(f"  optional {mod}: OK")
        except Exception:  # noqa: BLE001
            print(f"  optional {mod}: not installed (only needed for ML training / LLM / browser tests)")
    try:
        importlib.import_module("app.main")
        print("  app.main import: OK")
    except Exception as exc:  # noqa: BLE001
        ok = False
        print(f"  app.main import: FAILED ({type(exc).__name__}: {exc})")
    print("doctor: OK" if ok else "doctor: problems found")
    return 0 if ok else 1


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    sub.add_parser("setup").set_defaults(fn=cmd_setup)
    sub.add_parser("check-config").set_defaults(fn=cmd_check_config)
    p = sub.add_parser("migrate")
    p.add_argument("--new-only", action="store_true", help="create a new database only; never upgrade an existing one")
    p.set_defaults(fn=cmd_migrate)
    p = sub.add_parser("create-admin")
    p.add_argument("--email", required=True)
    p.add_argument("--name", required=True)
    p.set_defaults(fn=cmd_create_admin)
    p = sub.add_parser("add-real-deal")
    p.add_argument("--cik", required=True)
    p.add_argument("--fy", type=int, required=True)
    p.add_argument("--name", required=True)
    p.add_argument("--type", default="credit", choices=["credit", "m_and_a", "vendor_risk"])
    p.add_argument("--sector", default="n/a")
    p.add_argument("--owner", required=True)
    p.add_argument("--member", action="append")
    p.add_argument("--live", action="store_true", help="fetch from SEC/GLEIF/FRED now (needs VANTAGE_SEC_USER_AGENT)")
    p.set_defaults(fn=cmd_add_real_deal)
    sub.add_parser("backup").set_defaults(fn=cmd_backup)
    p = sub.add_parser("restore")
    p.add_argument("archive")
    p.add_argument("--yes", action="store_true")
    p.set_defaults(fn=cmd_restore)
    sub.add_parser("verify-audit").set_defaults(fn=cmd_verify_audit)
    p = sub.add_parser("inspect-db", help="read-only inspection of a SQLite file")
    p.add_argument("--path", required=True)
    p.set_defaults(fn=cmd_inspect_db)
    sub.add_parser("doctor", help="check dependencies and imports").set_defaults(fn=cmd_doctor)
    p = sub.add_parser("reset-dev")
    p.add_argument("--yes", action="store_true")
    p.set_defaults(fn=cmd_reset_dev)
    a = ap.parse_args()
    return a.fn(a)


if __name__ == "__main__":
    raise SystemExit(main())
